    private boolean CheckEmpty(String maLoai, String tenLoai){
        if (maLoai.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Mã loại không được để trống!");
                return true;
        }
        
        if (tenLoai.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Tên loại không được để trống!");
                return true;
        }
        
        return false;
    }
    
