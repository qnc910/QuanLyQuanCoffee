    private void LoadDanhSachMon(){
        try {           
        listmon.removeAll();
        DefaultListModel<String> model = new DefaultListModel<>();
        
        List<LoaiMon> ds = ApiLoaiMon.layDanhSachLoaiMon();
        
        for(LoaiMon lm : ds){
                model.addElement(lm.toString());
            }
        
        listmon.setModel(model);
        listmon.setSelectedIndex(0);
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
    Map<String, String> danhMucMap = new HashMap<>();
    private void LoadDanhMuc(){
        try {
            Connection con = Connect.ConnectDB.KetnoiDB();
            String sql = "Select * From loai_mon";
            PreparedStatement ps = con.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();
            cbo_DanhMuc.addItem("---Chọn loại món---");
            danhMucMap.put("---Chọn loại món---","");
            while(rs.next()){
                cbo_DanhMuc.addItem(rs.getString("ten_loai"));
                danhMucMap.put(rs.getString("ten_loai"), rs.getString("ma_loai"));
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
    private void LoadSanPham(){
        try {
            tbl_Mon.removeAll();
            String[] head = {"Mã món", "Tên món", "Giá", "Loại món", "Hình ảnh"};
            DefaultTableModel tb = new DefaultTableModel(head, 0);
            
            List<SanPhamDTO> ds = ApiSanpham.layDanhSachSanPham();
            
            for(SanPhamDTO sp : ds){
                tb.addRow(new Object[]{
                    sp.getMaMon(),
                    sp.getTenMon(),
                    sp.getGia(),
                    sp.getTenLoai(),
                    sp.getHinhAnh()
                });
            }
            
            tbl_Mon.getColumnModel().getColumn(4).setCellRenderer(new ImageRenderer());
            tbl_Mon.setRowHeight(60);
            tbl_Mon.setModel(tb);
            
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
